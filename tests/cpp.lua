-- fold shapes with clangd on C++ (tests/fixtures/cpp): namespaces,
-- template classes, lambdas, try/catch chains, brace initialisers.
local dir = vim.fn.expand("%:p:h")
local logf = io.open(dir .. "/result.log", "w")
local function log(s)
  logf:write(s, "\n")
  logf:flush()
end
local function wait(ms)
  vim.wait(ms, function()
    return false
  end)
end
local function check(name, got, want)
  log(("%s %s: %s (want %s)"):format(got == want and "PASS" or "FAIL", name, tostring(got), tostring(want)))
end
vim.defer_fn(function()
  log("TIMEOUT")
  vim.cmd("qall!")
end, 120000)
vim.schedule(function()
  local ok, err = pcall(function()
    vim.api.nvim_exec_autocmds("User", { pattern = "VeryLazy" })
    vim.o.lines, vim.o.columns = 40, 120
    vim.wait(30000, function()
      return #vim.lsp.get_clients({ bufnr = 0, name = "clangd" }) > 0
    end, 100)
    local FR = require("util.foldranges")
    vim.wait(15000, function()
      return FR.has(0)
    end, 50)
    wait(300)
    check("folds come from clangd", FR.has(0), true)
    local function fold(l) -- ,d on line l
      vim.cmd(("normal! %dG"):format(l))
      FR.toggle()
    end
    local function span(l)
      return vim.fn.foldclosed(l) .. ".." .. vim.fn.foldclosedend(l)
    end
    local function shape(l, want_span, want_text)
      vim.cmd("normal! zR")
      fold(l)
      local s = vim.fn.foldclosed(l)
      check("fold at " .. l, span(l) .. " " .. vim.fn.foldtextresult(s), want_span .. " " .. want_text)
    end
    check("the #include run folds on open", span(2), "1..3")
    check("include run fold line", vim.fn.foldtextresult(1), "#include ...")
    shape(6, "5..43", "namespace tree { ... }  // namespace tree")
    shape(7, "7..8", "/// Doc comment one ...")
    shape(11, "10..36", "class Tree { ... };")
    -- a wrapped method signature: parameters and body fold apart
    vim.cmd("normal! zR")
    fold(15)
    check("wrapped parameters fold on their own", span(15), "14..17")
    check("parameters fold line", vim.fn.foldtextresult(14), "    void insert( ... ) {")
    fold(15)
    fold(17)
    check("the body folds from the `) {` line", span(17), "17..23")
    check("body fold line", vim.fn.foldtextresult(17), "    ) { ... }")
    check("the parameters stay open above it", vim.fn.foldclosed(14), -1)
    vim.cmd("normal! zR")
    fold(19)
    check("an if branch folds to its `} else {`", span(19), "18..20")
    fold(21)
    check("the else over the folded if: their chain", span(18), "18..22")
    check("chain fold line", vim.fn.foldtextresult(18), "        if (left) { ... } else { ... }")
    shape(26, "25..31", "    std::vector<T> sorted() const { ... }")
    shape(28, "27..29", "        std::sort(copy.begin(), copy.end(), [](const T &a, const T &b) { ... });")
    shape(39, "38..41", "struct Config { ... };")
    shape(49, "48..51", "    std::vector<int> values = { ... };")
    shape(53, "52..55", "    tree::Config cfg{ ... };")
    shape(57, "56..58", "    try { ... } catch (const std::exception &e) {")
    shape(59, "58..60", "    } catch (const std::exception &e) { ... }")
    shape(62, "61..63", "    auto twice = [&](int x) { ... };")
    shape(46, "45..65", "int main() { ... }")
    vim.cmd("normal! zR")
  end)
  log(ok and "DONE" or ("ERROR: " .. tostring(err)))
  vim.cmd("qall!")
end)
