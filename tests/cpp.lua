-- fold shapes with clangd on C++ (tests/fixtures/cpp): namespaces,
-- template classes, lambdas, try/catch chains, brace initialisers.
local lib = dofile(debug.getinfo(1, "S").source:sub(2):match("^(.*)/[^/]*$") .. "/lib.lua")
lib.suite("clangd", function(t)
  t.check("the #include run folds on open", t.span(2), "1..3")
  t.check("include run fold line", vim.fn.foldtextresult(1), "#include ...")
  t.shape(6, "5..43", "namespace tree { ... }  // namespace tree")
  t.shape(7, "7..8", "/// Doc comment one ...")
  t.shape(11, "10..36", "class Tree { ... };")
  -- a wrapped method signature: parameters and body fold apart
  vim.cmd("normal! zR")
  t.fold(15)
  t.check("wrapped parameters fold on their own", t.span(15), "14..17")
  t.check("parameters fold line", vim.fn.foldtextresult(14), "    void insert( ... ) {")
  t.fold(15)
  t.fold(17)
  t.check("the body folds from the `) {` line", t.span(17), "17..23")
  t.check("body fold line", vim.fn.foldtextresult(17), "    ) { ... }")
  t.check("the parameters stay open above it", vim.fn.foldclosed(14), -1)
  vim.cmd("normal! zR")
  t.fold(19)
  t.check("an if branch folds to its `} else {`", t.span(19), "18..20")
  t.fold(21)
  t.check("the else over the folded if: their chain", t.span(18), "18..22")
  t.check("chain fold line", vim.fn.foldtextresult(18), "        if (left) { ... } else { ... }")
  t.shape(26, "25..31", "    std::vector<T> sorted() const { ... }")
  t.shape(28, "27..29", "        std::sort(copy.begin(), copy.end(), [](const T &a, const T &b) { ... });")
  t.shape(39, "38..41", "struct Config { ... };")
  t.shape(49, "48..51", "    std::vector<int> values = { ... };")
  t.shape(53, "52..55", "    tree::Config cfg{ ... };")
  t.shape(57, "56..58", "    try { ... } catch (const std::exception &e) {")
  t.shape(59, "58..60", "    } catch (const std::exception &e) { ... }")
  t.shape(62, "61..63", "    auto twice = [&](int x) { ... };")
  t.shape(46, "45..65", "int main() { ... }")
end)
