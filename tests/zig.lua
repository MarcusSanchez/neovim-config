-- fold shapes with zls (tests/fixtures/zig): zls stops a line short of
-- every closer like gopls, and nests if/else chains inside both branches
-- of an outer if/else — the case that once dragged a chain's fold onto
-- the outer `} else {`.
local lib = dofile(debug.getinfo(1, "S").source:sub(2):match("^(.*)/[^/]*$") .. "/lib.lua")
lib.suite("zls", function(t)
  t.fold(5)
  t.check("a struct folds through `};`", t.span(5), "4..15")
  t.check("struct fold line", vim.fn.foldtextresult(4), "const Node = struct { ... };")
  vim.cmd("normal! zR")
  -- if/else chains nested in both branches of an if/else
  t.fold(23)
  t.check("an inner if branch folds to its `} else {`", t.span(23), "23..25")
  t.check("inner if fold line", vim.fn.foldtextresult(23), "            if (node.left) |left| { ... } else {")
  t.fold(26)
  t.check("folding its else collapses the pair to the chain", t.span(23), "23..28")
  t.check("the chain stops at its own `}`, not the outer `} else {`", vim.fn.getline(29), "        } else {")
  t.check("chain fold line", vim.fn.foldtextresult(23), "            if (node.left) |left| { ... } else { ... }")
  t.check("the outer if branch stays open", vim.fn.foldclosed(22), -1)
  t.fold(30)
  t.check("the sibling chain in the else branch folds on its own", t.span(30), "30..32")
  t.check("the first chain is untouched", t.span(23), "23..28")
  t.fold(27)
  t.check(",d on the chain opens it, inner if still folded", t.span(23) .. " " .. vim.fn.foldclosed(26), "23..25 -1")
  vim.cmd("normal! zR")
  t.fold(22)
  t.check("the outer if branch folds to its `} else {`", t.span(22), "22..29")
  t.check("outer if fold line", vim.fn.foldtextresult(22), "        if (value < node.value) { ... } else {")
  t.fold(36)
  t.check("the outer else over a folded if: the whole chain", t.span(22), "22..36")
  vim.cmd("normal! zR")
  -- a wrapped signature: parameters and body fold apart, like Go's
  t.fold(40)
  t.check("wrapped parameters fold on their own", t.span(40), "39..42")
  t.check("parameters fold line", vim.fn.foldtextresult(39), "    pub fn describe( ... ) u32 {")
  t.fold(40) -- open them again
  t.fold(43)
  t.check("the body folds from the `) u32 {` line", t.span(43), "42..65")
  t.check("body fold line", vim.fn.foldtextresult(42), "    ) u32 { ... }")
  t.check("the parameters stay open above it", vim.fn.foldclosed(39), -1)
  t.fold(40)
  t.check("parameters over a folded body: the whole function", t.span(40), "39..65")
  vim.cmd("normal! zR")
  t.fold(45)
  t.check("a switch folds through `};`", vim.fn.foldtextresult(44), "        const total = switch (depth) { ... };")
  vim.cmd("normal! zR")
  t.fold(48)
  t.check("a labelled block prong folds through `},`", vim.fn.foldtextresult(47), "            else => blk: { ... },")
  vim.cmd("normal! zR")
  t.fold(53)
  t.check("an array literal", vim.fn.foldtextresult(52), "        const items = [_]u32{ ... };")
  vim.cmd("normal! zR")
  t.fold(57)
  t.check(
    "wrapped arguments through `) catch 0;`",
    vim.fn.foldtextresult(56),
    "        const sum = std.math.add( ... ) catch 0;"
  )
  vim.cmd("normal! zR")
  t.fold(62)
  t.check("a while loop", vim.fn.foldtextresult(61), "        while (depth > 0) { ... }")
  vim.cmd("normal! zR")
  t.fold(68)
  t.check("a doc comment run", vim.fn.foldtextresult(68), "/// Doc comment one ...")
  vim.cmd("normal! zR")
  t.fold(80)
  t.check("a struct literal", vim.fn.foldtextresult(79), "    const p = Point{ ... };")
  vim.cmd("normal! zR")
  t.fold(86)
  t.check("a for loop with captures", vim.fn.foldtextresult(85), "    for (buf, 0..) |*b, i| { ... }")
  vim.cmd("normal! zR")
  t.fold(102)
  t.check("a test block", vim.fn.foldtextresult(101), 'test "extras" { ... }')
end)
