-- fold shapes with zls (tests/fixtures/zig): zls stops a line short of
-- every closer like gopls, and nests if/else chains inside both branches
-- of an outer if/else — the case that once dragged a chain's fold onto
-- the outer `} else {`.
local dir = vim.fn.expand("%:p:h")
local logf = io.open(dir .. "/result.log", "w")
local function log(s)
  logf:write(s, "\n")
  logf:flush()
end
local function wait(ms)
  vim.wait(ms, function()
    return false
  end)
end
local function check(name, got, want)
  log(("%s %s: %s (want %s)"):format(got == want and "PASS" or "FAIL", name, tostring(got), tostring(want)))
end
vim.defer_fn(function()
  log("TIMEOUT")
  vim.cmd("qall!")
end, 120000)
vim.schedule(function()
  local ok, err = pcall(function()
    vim.api.nvim_exec_autocmds("User", { pattern = "VeryLazy" })
    vim.o.lines, vim.o.columns = 40, 120
    vim.wait(30000, function()
      return #vim.lsp.get_clients({ bufnr = 0, name = "zls" }) > 0
    end, 100)
    local FR = require("util.foldranges")
    vim.wait(15000, function()
      return FR.has(0)
    end, 50)
    wait(300)
    check("folds come from zls", FR.has(0), true)
    local function fold(l) -- ,d on line l
      vim.cmd(("normal! %dG"):format(l))
      FR.toggle()
    end
    local function span(l)
      return vim.fn.foldclosed(l) .. ".." .. vim.fn.foldclosedend(l)
    end
    fold(5)
    check("a struct folds through `};`", span(5), "4..15")
    check("struct fold line", vim.fn.foldtextresult(4), "const Node = struct { ... };")
    vim.cmd("normal! zR")
    -- if/else chains nested in both branches of an if/else
    fold(23)
    check("an inner if branch folds to its `} else {`", span(23), "23..25")
    check("inner if fold line", vim.fn.foldtextresult(23), "            if (node.left) |left| { ... } else {")
    fold(26)
    check("folding its else collapses the pair to the chain", span(23), "23..28")
    check("the chain stops at its own `}`, not the outer `} else {`", vim.fn.getline(29), "        } else {")
    check("chain fold line", vim.fn.foldtextresult(23), "            if (node.left) |left| { ... } else { ... }")
    check("the outer if branch stays open", vim.fn.foldclosed(22), -1)
    fold(30)
    check("the sibling chain in the else branch folds on its own", span(30), "30..32")
    check("the first chain is untouched", span(23), "23..28")
    fold(27)
    check(",d on the chain opens it, inner if still folded", span(23) .. " " .. vim.fn.foldclosed(26), "23..25 -1")
    vim.cmd("normal! zR")
    fold(22)
    check("the outer if branch folds to its `} else {`", span(22), "22..29")
    check("outer if fold line", vim.fn.foldtextresult(22), "        if (value < node.value) { ... } else {")
    fold(36)
    check("the outer else over a folded if: the whole chain", span(22), "22..36")
    vim.cmd("normal! zR")
    -- a wrapped signature: parameters and body fold apart, like Go's
    fold(40)
    check("wrapped parameters fold on their own", span(40), "39..42")
    check("parameters fold line", vim.fn.foldtextresult(39), "    pub fn describe( ... ) u32 {")
    fold(40) -- open them again
    fold(43)
    check("the body folds from the `) u32 {` line", span(43), "42..65")
    check("body fold line", vim.fn.foldtextresult(42), "    ) u32 { ... }")
    check("the parameters stay open above it", vim.fn.foldclosed(39), -1)
    fold(40)
    check("parameters over a folded body: the whole function", span(40), "39..65")
    vim.cmd("normal! zR")
    fold(45)
    check("a switch folds through `};`", vim.fn.foldtextresult(44), "        const total = switch (depth) { ... };")
    vim.cmd("normal! zR")
    fold(48)
    check("a labelled block prong folds through `},`", vim.fn.foldtextresult(47), "            else => blk: { ... },")
    vim.cmd("normal! zR")
    fold(53)
    check("an array literal", vim.fn.foldtextresult(52), "        const items = [_]u32{ ... };")
    vim.cmd("normal! zR")
    fold(57)
    check(
      "wrapped arguments through `) catch 0;`",
      vim.fn.foldtextresult(56),
      "        const sum = std.math.add( ... ) catch 0;"
    )
    vim.cmd("normal! zR")
    fold(62)
    check("a while loop", vim.fn.foldtextresult(61), "        while (depth > 0) { ... }")
    vim.cmd("normal! zR")
    fold(68)
    check("a doc comment run", vim.fn.foldtextresult(68), "/// Doc comment one ...")
    vim.cmd("normal! zR")
    fold(80)
    check("a struct literal", vim.fn.foldtextresult(79), "    const p = Point{ ... };")
    vim.cmd("normal! zR")
    fold(86)
    check("a for loop with captures", vim.fn.foldtextresult(85), "    for (buf, 0..) |*b, i| { ... }")
    vim.cmd("normal! zR")
    fold(102)
    check("a test block", vim.fn.foldtextresult(101), 'test "extras" { ... }')
    vim.cmd("normal! zR")
  end)
  log(ok and "DONE" or ("ERROR: " .. tostring(err)))
  vim.cmd("qall!")
end)
