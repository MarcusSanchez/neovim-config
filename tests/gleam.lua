-- fold shapes with the gleam language server (tests/fixtures/gleam): it
-- folds only top-level declarations, and a wrapped signature from its `)`
-- line, so treesitter supplies the bracket regions inside (see
-- util/foldranges.lua's supplements).
local dir = vim.fn.expand("%:p:h")
local logf = io.open(dir .. "/result.log", "w")
local function log(s)
  logf:write(s, "\n")
  logf:flush()
end
local function wait(ms)
  vim.wait(ms, function()
    return false
  end)
end
local function check(name, got, want)
  log(("%s %s: %s (want %s)"):format(got == want and "PASS" or "FAIL", name, tostring(got), tostring(want)))
end
vim.defer_fn(function()
  log("TIMEOUT")
  vim.cmd("qall!")
end, 120000)
vim.schedule(function()
  local ok, err = pcall(function()
    vim.api.nvim_exec_autocmds("User", { pattern = "VeryLazy" })
    vim.o.lines, vim.o.columns = 40, 120
    vim.wait(30000, function()
      return #vim.lsp.get_clients({ bufnr = 0, name = "gleam" }) > 0
    end, 100)
    local FR = require("util.foldranges")
    vim.wait(15000, function()
      return FR.has(0)
    end, 50)
    wait(300)
    check("folds come from the gleam server", FR.has(0), true)
    local function fold(l) -- ,d on line l
      vim.cmd(("normal! %dG"):format(l))
      FR.toggle()
    end
    local function span(l)
      return vim.fn.foldclosed(l) .. ".." .. vim.fn.foldclosedend(l)
    end
    check("imports fold on open", span(2), "1..4")
    check("imports fold line", vim.fn.foldtextresult(1), "import ...")
    check("the rest of the file is open", vim.fn.foldclosed(6), -1)
    vim.cmd("normal! zR")
    fold(7)
    check("a custom type", vim.fn.foldtextresult(6), "pub type Shape { ... }")
    fold(14)
    check(
      "a wrapped constructor's fields (treesitter)",
      span(14) .. " " .. vim.fn.foldtextresult(13),
      "13..17   Node( ... )"
    )
    fold(22)
    check("a case expression (treesitter)", span(22) .. " " .. vim.fn.foldtextresult(21), "21..27   case shape { ... }")
    vim.cmd("normal! zR")
    fold(24)
    check("a clause's block", vim.fn.foldtextresult(23), "    Rect(width, height) -> { ... }")
    vim.cmd("normal! zR")
    -- the server's range for a wrapped signature starts on its `)` line;
    -- treesitter's function node gives the whole, so it folds like Go's
    fold(31)
    check("wrapped parameters fold on their own", span(31), "30..33")
    check("parameters fold line", vim.fn.foldtextresult(30), "pub fn insert( ... ) -> Tree(Int) {")
    fold(31) -- open them again
    fold(33)
    check("the body folds from the `) -> Tree(Int) {` line", span(35), "33..45")
    check("body fold line", vim.fn.foldtextresult(33), ") -> Tree(Int) { ... }")
    check("the parameters stay open above it", vim.fn.foldclosed(30), -1)
    fold(31)
    check("parameters over a folded body: the whole function", span(31), "30..45")
    check("whole-function fold line", vim.fn.foldtextresult(30), "pub fn insert( ... ) -> Tree(Int) { ... }")
    vim.cmd("normal! zR")
    fold(40)
    check("a nested case clause block", vim.fn.foldtextresult(39), "        False -> { ... }")
    vim.cmd("normal! zR")
    fold(51)
    check("an anonymous function in a pipeline", vim.fn.foldtextresult(50), "    |> list.map(fn(x) { ... })")
    vim.cmd("normal! zR")
    fold(55)
    check("a list literal", vim.fn.foldtextresult(54), "  let names = [ ... ]")
    vim.cmd("normal! zR")
    fold(60)
    check("wrapped arguments", vim.fn.foldtextresult(59), "  let message = int.to_string( ... )")
    vim.cmd("normal! zR")
    fold(64)
    check("a case over a list", vim.fn.foldtextresult(63), "  case names { ... }")
    vim.cmd("normal! zR")
    fold(76)
    check("a doc comment run", vim.fn.foldtextresult(76), "/// Documentation line one ...")
    vim.cmd("normal! zR")
    fold(92)
    check("a record update", vim.fn.foldtextresult(91), "    Config( ... )")
    vim.cmd("normal! zR")
    fold(96)
    check("a tuple", vim.fn.foldtextresult(95), "  let pair = #( ... )")
    vim.cmd("normal! zR")
    fold(100)
    check("a bit array closes with `>>`", vim.fn.foldtextresult(99), "  let bits = << ... >>")
    vim.cmd("normal! zR")
    fold(105)
    check("an anonymous function's wrapped parameters", vim.fn.foldtextresult(104), "  let add = fn( ... ) {")
    fold(108)
    check("its body from the `) {` line", vim.fn.foldtextresult(107), "  ) { ... }")
    vim.cmd("normal! zR")
  end)
  log(ok and "DONE" or ("ERROR: " .. tostring(err)))
  vim.cmd("qall!")
end)
